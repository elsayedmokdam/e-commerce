import type { Metadata } from "next";
import { Exo } from "next/font/google";
import "./globals.css";
import React from "react";
import { Navbar } from "@/components/navbar/Navbar";
import { Footer } from "@/components/footer/Footer";
import { Toaster } from "react-hot-toast";
import MySessionProvider from "./_providers/MySessionProvider";
import CartContextProvider from "./_providers/context/CartContextProvider";
import { getLogedUserCartAction } from "@/components/shared/product-card/cart.action";
import { HttpResult } from "@/services/utils/http";
import { CartResponse } from "@/services/types/cart_interface";
const exo = Exo({
  variable: "--font-exo",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: {
    default: "Next.js App",
    template: "%s | Next.js App",
  },
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const response: HttpResult<CartResponse | null> =
    await getLogedUserCartAction();
  let userCart = null;
  if (response.ok) {
    userCart = response.data;
  }
  return (
    <html lang="en" className={`${exo.variable}`}>
      <body>
        {/* Client Boundary Pattern */}
        <MySessionProvider>
          <CartContextProvider userCart={userCart}>
            <Navbar />
            {children}
            <Footer />
            <Toaster position="top-center" />
          </CartContextProvider>
        </MySessionProvider>
      </body>
    </html>
  );
}
